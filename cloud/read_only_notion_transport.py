"""Constrain a supplied transport to full-snapshot Notion read routes.

The delegate is responsible for its own authenticated origin, TLS, redirect
policy, error handling and rate limits. This wrapper does not authenticate a
snapshot, enforce the central writer lock, or authorize a reconciliation.
"""
import re


class ReadOnlyTransportBlocked(RuntimeError):
    """Fixed diagnostic, never include path, headers or request data."""


_IDENTIFIER = r"[A-Za-z0-9_-]{1,128}"
_PROPERTY = r"(?:[A-Za-z0-9_-]|%[0-9A-Fa-f]{2}){1,128}"
_CURSOR = r"[A-Za-z0-9_-]{1,512}"
_PAGE_QUERY = rf"\?page_size=100(?:&start_cursor={_CURSOR})?"


class ReadOnlyNotionTransport:
    """Allow only the request forms generated by NotionStore.snapshot_all()."""

    def __init__(self, data_source_id, delegate):
        if (not isinstance(data_source_id, str)
                or not re.fullmatch(r"[0-9a-fA-F-]{1,64}", data_source_id)
                or not callable(delegate)):
            raise ReadOnlyTransportBlocked("read_only_transport_blocked")
        self._source_path = "/data_sources/" + data_source_id
        self._delegate = delegate

    def __call__(self, method, path, body, headers):
        valid = False
        if isinstance(path, str):
            if method == "POST" and path == self._source_path + "/query":
                valid = (isinstance(body, dict) and set(body) in ({"page_size"}, {"page_size", "start_cursor"})
                         and type(body.get("page_size")) is int and body["page_size"] == 100
                         and ("start_cursor" not in body or isinstance(body["start_cursor"], str)
                              and re.fullmatch(_CURSOR, body["start_cursor"]) is not None))
            elif method == "GET" and body is None:
                valid = (path == self._source_path
                         or re.fullmatch(rf"/blocks/{_IDENTIFIER}/children{_PAGE_QUERY}", path) is not None
                         or re.fullmatch(rf"/pages/{_IDENTIFIER}/properties/{_PROPERTY}{_PAGE_QUERY}", path) is not None
                         and not re.search(r"%(?:00|0[1-9a-f]|1[0-9a-f]|2e|2f|3f|23|25|5c|7f)", path, re.I))
        if (not valid or not isinstance(headers, dict)
                or set(headers) != {"Authorization", "Notion-Version", "Content-Type"}
                or headers.get("Content-Type") != "application/json"
                or not isinstance(headers.get("Authorization"), str)
                or not headers["Authorization"].startswith("Bearer ")
                or not isinstance(headers.get("Notion-Version"), str)
                or any(re.search(r"[\x00-\x1f\x7f]", value) for value in headers.values())):
            raise ReadOnlyTransportBlocked("read_only_transport_blocked")
        return self._delegate(method, path, body, headers)
